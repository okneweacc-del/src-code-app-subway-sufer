using System.Collections;
using System.Collections.Generic;
using InApp;
using Kiloo.Common.Backend.PurchaseValidation;
using UnityEngine;

namespace InAppPurchase.Internal;

public class EditorPurchaseProvider : IPurchaseProvider
{
	private const float INITIALIZE_FAIL_CHANCE = 0f;

	private const float PRODUCTREQUEST_FAIL_CHANCE = 0f;

	private const float PRODUCTREQUEST_DELAY = 0f;

	private const float PRODUCTREQUEST_INVALID_CHANCE = 0f;

	private const float PURCHASE_DELAY = 0f;

	private const float PURCHASE_FAIL_CHANCE = 0f;

	private static readonly string[] DUMMY_PRICES_LOCALIZED = new string[7] { "$1.95", "0,79 €", "59,00 kr", "$19.95", "$1.95", "$3.95", "$9.95" };

	private static readonly bool USE_SINGLE_RESTORE_INSTEAD_OF_PURCHASE = false;

	private PurchaseDelegate _purchaseDelegate;

	private ProductInfoRequestDelegate _productRequestDelegate;

	private ItemRestoredDelegate _itemRestoredDelegate;

	private RestorePurchaseFinishedDelegate _restorePurchaseFinishedDelegate;

	private IPurchaseValidationServer _purchaseValidationServer;

	private IInAppManager _inAppManager;

	private MonoBehaviour _coroutineBehaviour;

	public static readonly List<string> LIST_OF_IDS_TO_RESTORE = new List<string> { "com.kiloo.subwayboard.cherry", "com.kiloo.subwaycharacter.coco", "com.kiloo.subways.adremovaltier1" };

	public bool IsValidationServerSpecified => _purchaseValidationServer != null;

	public void Init(IInAppManager inAppManager, IPurchaseValidationServer purchaseValidationServer)
	{
		_inAppManager = inAppManager;
		_purchaseDelegate = inAppManager.PurchaseRequestCallback;
		_productRequestDelegate = inAppManager.ProductInfoRequestCallback;
		_itemRestoredDelegate = inAppManager.ItemRestoredCallback;
		_restorePurchaseFinishedDelegate = inAppManager.RestoreRequestFinishedCallback;
		_purchaseValidationServer = purchaseValidationServer;
		GameObject gameObject = new GameObject("EditorPurchaseProviderCoroutines_autogenerated");
		Object.DontDestroyOnLoad(gameObject);
		_coroutineBehaviour = gameObject.AddComponent<NewMonoBehaviour>();
		if (Random.value > 0f)
		{
			_inAppManager.InitFinishedCallback(success: true);
		}
		else
		{
			_inAppManager.InitFinishedCallback(success: false);
		}
	}

	public bool CanMakePurchases()
	{
		return true;
	}

	public void RequestProductInfo(string[] productIds)
	{
		_coroutineBehaviour.StartCoroutine(ProductRequestCoroutine(productIds));
	}

	public bool StartPurchase(string productId)
	{
		return StartPurchase(productId, null);
	}

	public bool StartPurchase(string productId, string cookie)
	{
		if (_purchaseDelegate != null)
		{
			_coroutineBehaviour.StartCoroutine(PurchaseCoroutine(productId));
			return true;
		}
		return false;
	}

	public void FinishPurchase(string productId, string transactionId, string purchaseToken)
	{
	}

	public bool RestoreNonConsumablePurchases(string[] productIds)
	{
		_coroutineBehaviour.StartCoroutine(RestoreCoroutine(productIds));
		return true;
	}

	private IEnumerator ProductRequestCoroutine(string[] productIds)
	{
		yield return new WaitForSeconds(0f);
		bool success = Random.value > 0f;
		ProductRequestResultInfo[] productInfo;
		if (success)
		{
			productInfo = new ProductRequestResultInfo[productIds.Length];
			for (int i = 0; i < productInfo.Length; i++)
			{
				productInfo[i].Init(productIds[i], DUMMY_PRICES_LOCALIZED[i % DUMMY_PRICES_LOCALIZED.Length], "Editor title", "Editor description");
			}
		}
		else
		{
			productInfo = new ProductRequestResultInfo[0];
		}
		_productRequestDelegate?.Invoke(success, productInfo);
	}

	private IEnumerator PurchaseCoroutine(string productId)
	{
		yield return new WaitForSeconds(0f);
		IPurchaseValidationResult validationResult = null;
		if (_purchaseValidationServer != null)
		{
			_purchaseValidationServer.ValidateTransaction(productId, "EditorPurchaseReceipt", (IPurchaseValidationResult purchaseValidationResult) =>
			{
				validationResult = purchaseValidationResult;
			});
			if (validationResult == null)
			{
				yield return null;
			}
		}
		PurchaseResult result;
		if (Random.value < 0f)
		{
			result = PurchaseResult.Failed;
		}
		else
		{
			result = PurchaseResult.Completed;
			PlayerPrefs.SetString("restore" + productId, productId);
			PlayerPrefs.Save();
		}
		if (USE_SINGLE_RESTORE_INSTEAD_OF_PURCHASE && !InAppData.inAppData[productId].isConsumable)
		{
			_itemRestoredDelegate(productId, "dummytransactionid", "dummycookie");
		}
		else
		{
			_purchaseDelegate(productId, "dummytransactionid", "qwertyuiop[;.,nbvcxasdfghjklqwertyuiopasdfghjklzxcvbnm,qwertyuio1234567uj9ikm2wszx8ujn3e4d7yhn45rfvc76yh6tgb89ikjm7yhb0okl,e3dc8uhjnmersd8iokjetr", "dummycookie", result, validationResult);
		}
	}

	private IEnumerator RestoreCoroutine(string[] productIds)
	{
		yield return new WaitForSeconds(0f);
		RestoreFinishedResult result;
		if (Random.value < 0f)
		{
			result = RestoreFinishedResult.Failed;
		}
		else
		{
			int num = 0;
			for (int i = 0; i < productIds.Length; i++)
			{
				if (LIST_OF_IDS_TO_RESTORE.Contains(productIds[i]))
				{
					_itemRestoredDelegate(productIds[i], "dummytransactionid", "dummycookie");
					num++;
				}
			}
			result = ((num <= 0) ? RestoreFinishedResult.NothingToRestore : RestoreFinishedResult.Completed);
		}
		_restorePurchaseFinishedDelegate(result);
	}
}
